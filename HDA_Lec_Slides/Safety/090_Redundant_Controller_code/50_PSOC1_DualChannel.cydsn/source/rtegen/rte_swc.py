def create_one_swc_header(root, config, swcname):

    #Create and open file    
    out_file = config["path_out"] + "\\" + swcname.lower() + ".h"
    fout = open(out_file,'w')
    
    rline = "/**************************************************\n"
    fout.write(rline)
    
    rline = " ** Software Component "+swcname + "\n"
    fout.write(rline)
  
    rline = " ** autogenerated by H-DA RTE Generator\n"
    fout.write(rline)
    
    rline = " **************************************************/\n\n"
    fout.write(rline)
    
    filename = swcname.upper()
    rline = "#ifndef " + filename + "_H\n"
    fout.write(rline)
    
    rline = "#define " + filename + "_H\n\n"
    fout.write(rline)
    
    rline = "\n/* Runnables */\n"
    fout.write(rline)

    for runnable in root.iter("runnable"):
        if runnable.get("component") == swcname:
            rline = "void " + runnable.get("name") + "();\n\n"
            fout.write(rline)

    fout.write("#endif /* include guard */\n\n")  

    fout.close()
  
