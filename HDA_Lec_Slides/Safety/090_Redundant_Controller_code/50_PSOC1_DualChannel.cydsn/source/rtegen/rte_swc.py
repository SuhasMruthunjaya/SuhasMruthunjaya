## create_one_signal_class
def create(root, config):
    
    #Challenge: We have several entries for the components (historical legacy)
    swc_list = list()
    
    for runnable in root.iter('runnable'):
        swc_name = runnable.get("component")

        if swc_list.count(swc_name) == 0:
            #SWC not considered yet
            print("   Creating SWC: ", swc_name)
            
            create_one_swc_source(root, config, swc_name)
            create_one_swc_header(root, config, swc_name)
            
            #Consider every name only ones
            swc_list.append(swc_name)
  
