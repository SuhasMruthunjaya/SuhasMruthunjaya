## create_one_swc_source
def create_one_swc_source(root, config, swcname):
    #Create and open file    
    out_file = config["path_out"] + "\\" + swcname.lower() + ".c"
    fout = open(out_file,'w')
    
    rline = "/**************************************************\n"
    fout.write(rline)
    
    rline = " ** Software Component "+swcname + "\n"
    fout.write(rline)
  
    rline = " ** autogenerated by H-DA RTE Generator\n"
    fout.write(rline)
    
    rline = " **************************************************/\n\n"
    fout.write(rline)
    
    rline = "#include \"rte.h\"\n"
    fout.write(rline)

    rline = "#include \"rte_signalpool.h\"\n"
    fout.write(rline)

    rline = "\n#include \"" + swcname.lower() + ".h\"\n"
    fout.write(rline)
    
    
    rline = "\n/* Runnables */\n"
    fout.write(rline)

    for runnable in root.iter("runnable"):
        if runnable.get("component") == swcname:
            rline = "void " + runnable.get("name") + "()\n"
            fout.write(rline)
            rline="{\n\n";
            fout.write(rline)
            rline="   /* Enter your code here */\n";
            fout.write(rline)
            rline="}\n";
            fout.write(rline)

    fout.close()    

  
